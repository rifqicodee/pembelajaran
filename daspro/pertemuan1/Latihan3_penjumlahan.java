public class Latihan3_penjumlahan {

    public static void main(String[] args) {
        int a,b,c,jumlah;
        a = 10;
        b = 5;
        c = 20;
        jumlah = a + b + c;
        System.out.println("Nilai a = " + a);
        System.out.println("Nilai b = " + b);
        System.out.println("Nilai c = " + c);

        System.out.println("Hasil penjumlahan = " + jumlah);
    }
}