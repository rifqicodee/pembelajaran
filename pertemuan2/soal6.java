public class soal6 {
    public static void main(String[] args) {
        int sisi =  100;
        int r = sisi / 2;
        double phi = 3.14; 
        int persegi = sisi * sisi;
        double lingkaran = phi * r * r;
        double hasil = persegi - lingkaran;

        System.out.println("Luas tidak ditanami adalah = " + hasil);
    }
}
